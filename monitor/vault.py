"""Write a daily AI-usage summary note into the Obsidian vault."""
import time
from datetime import datetime

from . import config, db


def write_daily_note():
    if not config.WRITE_VAULT:
        return
    try:
        config.VAULT_NOTE_DIR.mkdir(parents=True, exist_ok=True)
    except Exception as e:
        print(f"[vault] cannot create note dir: {e}")
        return

    today = datetime.now().strftime("%Y-%m-%d")
    start = int(datetime.now().replace(hour=0, minute=0, second=0, microsecond=0).timestamp())

    with db.connect() as c:
        rows = c.execute(
            "SELECT source, COUNT(*) calls, "
            "COALESCE(SUM(input+output+cache_write+cache_read),0) tokens, "
            "COALESCE(SUM(cost),0) cost "
            "FROM events WHERE ts>=? GROUP BY source ORDER BY cost DESC",
            (start,),
        ).fetchall()
        tot = c.execute(
            "SELECT COALESCE(SUM(cost),0) c, "
            "COALESCE(SUM(input+output+cache_write+cache_read),0) t "
            "FROM events WHERE ts>=?", (start,)).fetchone()

    lines = [
        f"# AI Usage — {today}",
        "",
        "*Auto-generated by ai-usage-monitor.*",
        "",
        "## AI Usage",
        f"- **Total cost today:** ${tot['c']:.4f}",
        f"- **Total tokens today:** {tot['t']:,}",
        "",
        "| Tool | Calls | Tokens | Cost |",
        "|---|---:|---:|---:|",
    ]
    for r in rows:
        lines.append(
            f"| {r['source']} | {r['calls']:,} | {r['tokens']:,} | ${r['cost']:.4f} |")
    if not rows:
        lines.append("| — | 0 | 0 | $0.0000 |")
    lines += ["", f"_Updated {datetime.now().strftime('%H:%M')}_  #ai-usage", ""]

    note = config.VAULT_NOTE_DIR / f"{today}.md"
    try:
        note.write_text("\n".join(lines), encoding="utf-8")
    except Exception as e:
        print(f"[vault] write failed: {e}")
